// PLAN.md 11c: writes edge/app.roc from conformance/app.roc, so the edge app has the same route modules as the local
// conformance app (it is not a second copy that can drift). The changes: the route `/edge` (EdgeRoutes.roc), and
// `scheduled!` of EdgeRoutes.roc (the crons of the edge run, API.md AQ12) in `Worker.new`. Each change must apply once,
// else the script fails. edge/build.sh runs it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
let s = readFileSync(join(here, '../conformance/app.roc'), 'utf8');
const once = (what, from, to) => {
  const n = s.split(from).length - 1;
  if (n !== 1) throw new Error(`edge/gen-app.mjs: ${what}: found ${n} times in conformance/app.roc, want 1`);
  s = s.replace(from, to);
};
once('the header comment', '## The conformance app (PLAN.md 8c)', '## Generated by edge/gen-app.mjs from conformance/app.roc. Do not edit.\n## The edge app (PLAN.md 11c): the conformance app and the route `/edge` (EdgeRoutes.roc).\n## The conformance app (PLAN.md 8c)');
once('the last import', '\nimport BodyRoutes\n', '\nimport BodyRoutes\nimport EdgeRoutes\n');
once('the 404 route', '\t\t_ => Response.from_text(404, "no route")', '\t\t["edge", .. as rest] => EdgeRoutes.route!(req, rest)\n\t\t_ => Response.from_text(404, "no route")');
once('scheduled! of Worker.new', 'Worker.new({ fetch!, scheduled!, ', 'Worker.new({ fetch!, scheduled!: EdgeRoutes.scheduled!, ');
writeFileSync(join(here, 'app.roc'), s);
