const open = (url) => new Promise((ok, bad) => { const w = new WebSocket(url); w.msgs = []; w.onmessage = (e) => w.msgs.push(String(e.data)); w.onopen = () => ok(w); w.onerror = (e) => bad(e); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const a = await open('ws://localhost:8797/room/r1?name=ann');
const b = await open('ws://localhost:8797/room/r1?name=bob');
await sleep(300);
a.send(JSON.stringify({ text: 'hi bob' }));
await sleep(300);
b.send('ping');
await sleep(300);
a.send('not json');
await sleep(300);
console.log('ann got', a.msgs, 'bob got', b.msgs);
a.close(1000, 'bye'); b.close(1000, 'bye');
await sleep(300);
const e = await open('ws://localhost:8797/echo');
e.send('hello'); await sleep(300);
console.log('echo got', e.msgs);
e.close(1000, 'done'); await sleep(500);
const r = await fetch('http://localhost:8797/room/r1'); console.log('no upgrade ->', r.status);
process.exit(0);
